/**
 * ───────────────────────────────────────────────────────────────────────────
 *  LEVEL 2 CINEMA CUTSCENES — story beats for the Scrapcraft Story Cinema
 * ───────────────────────────────────────────────────────────────────────────
 *
 * Authored timeline cutscenes (see src/cinema/Timeline.js) that form the
 * cinema playlist. They play through the game's own CutsceneDirector
 * (game.cinema), which also gates player.tick — so while a beat runs, the
 * director owns the camera outright.
 *
 * v3 direction: the explorer. No more orbits. Each beat is a flight —
 * the camera travels through the yard like a player would, skimming low,
 * climbing for aerials, pushing through spaces. Keyframes are generated by
 * exploreKeys(): curved 3D paths between points of interest, with the look
 * target leading the motion. Depth pops because the camera moves through it.
 *
 * Camera keyframes constrained: x∈[0,128], z∈[0,130], y∈[3,40] (clamped in
 * the generator as a safety net). Yard center ≈ {x:64, z:62}. Bands:
 * 0 gate/shed (z 0–31), 1 industrial (z 32–63), 2 circuit city + oval
 * (z 64–95), 3 deep yard (z 96–127).
 *
 * Subtitle lines are the son's own where marked; the rest are narration in
 * the yard's register — short, warm, no wasted words. Fewer lines than v1,
 * held longer: the camera does the talking.
 */

